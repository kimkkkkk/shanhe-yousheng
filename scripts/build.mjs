#!/usr/bin/env node
/**
 * 山河有声 · 生产构建
 * 生成纯静态 dist/，可直接部署到任意 HTTPS 静态托管。
 *
 * 用法：
 *   node scripts/build.mjs
 *   npm run build
 */
import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PRODUCTION_HEADERS } from '../config/security.mjs';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const DIST = join(ROOT, 'dist');
const APP_VERSION = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8')).version;
const REQUIRED = [
  'index.html',
  'manifest.webmanifest',
  'sw.js',
  '.nojekyll',
  '_headers',
  'robots.txt',
  'icons/icon.svg',
  'icons/icon-192.png',
  'icons/icon-512.png',
  'icons/icon-maskable-512.png',
  'icons/apple-touch-icon.png',
  'assets/demo-huangshan.svg',
  'assets/demo-westlake.svg',
  'assets/demo-coast.svg',
  'assets/demo-village.svg',
  'assets/demo-desert.svg'
];

console.log('\n  山河有声 · production build\n');

await rm(DIST, { recursive: true, force: true });
await mkdir(DIST, { recursive: true });

// 只复制运行时需要的文件，避免把测试、截图、开发脚本带上生产环境。
for (const file of ['index.html', 'manifest.webmanifest', 'sw.js']) {
  await cp(join(ROOT, file), join(DIST, file));
}
for (const dir of ['src', 'assets', 'icons']) {
  await cp(join(ROOT, dir), join(DIST, dir), { recursive: true });
}

// 平台安全头：Netlify / Cloudflare Pages 原生识别 _headers。
const cacheSections = [
  { path: '/index.html', cache: 'no-cache' },
  { path: '/', cache: 'no-cache' },
  { path: '/sw.js', cache: 'no-cache' },
  { path: '/manifest.webmanifest', cache: 'no-cache' },
  { path: '/src/*', cache: 'no-cache' },
  { path: '/assets/*', cache: 'public, max-age=3600' },
  { path: '/icons/*', cache: 'public, max-age=86400' }
];
const headerLines = ['# Generated by scripts/build.mjs'];
headerLines.push('/*');
for (const [name, value] of Object.entries(PRODUCTION_HEADERS)) {
  headerLines.push(`  ${name}: ${value}`);
}
headerLines.push('');
for (const { path, cache } of cacheSections) {
  headerLines.push(path, `  Cache-Control: ${cache}`, '');
}
await writeFile(join(DIST, '_headers'), `${headerLines.join('\n').trim()}\n`, 'utf8');

// GitHub Pages 会忽略下划线开头的文件；.nojekyll 防止它改写静态资源路径。
await writeFile(join(DIST, '.nojekyll'), '', 'utf8');
await writeFile(
  join(DIST, 'robots.txt'),
  'User-agent: *\nAllow: /\n\n# 山河有声：照片只在本机处理，不上传服务器。\n',
  'utf8'
);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else files.push(full);
  }
  return files;
}

const filesForHash = (await walk(DIST)).filter(
  (file) => !file.endsWith(`${sep}sw.js`) && !file.endsWith(`${sep}.deploy-info.json`)
);
filesForHash.sort();
const digest = createHash('sha256');
for (const file of filesForHash) {
  digest.update(relative(DIST, file).split(sep).join('/'));
  digest.update(await readFile(file));
}
const buildId = digest.digest('hex').slice(0, 12);

const swPath = join(DIST, 'sw.js');
const sourceSw = await readFile(swPath, 'utf8');
const builtSw = sourceSw.replace(/const VERSION = '[^']+';/, `const VERSION = '${APP_VERSION}-${buildId}';`);
if (builtSw === sourceSw) {
  throw new Error('无法写入 Service Worker 构建版本，请检查 sw.js 的 VERSION 定义');
}
await writeFile(swPath, builtSw, 'utf8');

// 校验 Service Worker 预缓存清单，任何缺文件都在构建阶段失败。
const coreMatch = /const CORE = \[([\s\S]*?)\];/.exec(builtSw);
if (!coreMatch) throw new Error('sw.js 中找不到 CORE 预缓存清单');
const corePaths = [...coreMatch[1].matchAll(/'([^']+)'/g)].map((match) => match[1]);
for (const path of corePaths) {
  if (path === '/') continue;
  const target = join(DIST, path.replace(/^\//, ''));
  try {
    await stat(target);
  } catch {
    throw new Error(`Service Worker 预缓存文件不存在: ${path}`);
  }
}

for (const file of REQUIRED) {
  try {
    await stat(join(DIST, file));
  } catch {
    throw new Error(`构建缺少必需文件: ${file}`);
  }
}

// 校验 HTML 中的根路径引用与 manifest 图标。
const html = await readFile(join(DIST, 'index.html'), 'utf8');
const refs = [...html.matchAll(/(?:src|href)="(\/[^"#?]+)"/g)].map((match) => match[1]);
for (const ref of refs) {
  if (ref === '/') continue;
  try {
    await stat(join(DIST, ref.replace(/^\//, '')));
  } catch {
    throw new Error(`index.html 引用了不存在的资源: ${ref}`);
  }
}
const manifest = JSON.parse(await readFile(join(DIST, 'manifest.webmanifest'), 'utf8'));
for (const icon of manifest.icons || []) {
  try {
    await stat(join(DIST, String(icon.src).replace(/^\//, '')));
  } catch {
    throw new Error(`manifest 图标不存在: ${icon.src}`);
  }
}

const allFiles = (await walk(DIST)).sort();
let totalBytes = 0;
for (const file of allFiles) totalBytes += (await stat(file)).size;
const infoBase = {
  name: 'shanhe-yousheng',
  version: APP_VERSION,
  buildId,
  builtAt: new Date().toISOString(),
  deployment: 'static HTTPS (root path)',
  basePath: '/',
  runtime: 'offline-first PWA',
  requiresNode: false
};
let metadataBytes = totalBytes;
let infoText = '';
for (let i = 0; i < 2; i++) {
  infoText = `${JSON.stringify({ ...infoBase, fileCount: allFiles.length + 1, totalBytes: metadataBytes }, null, 2)}\n`;
  metadataBytes = totalBytes + Buffer.byteLength(infoText);
}
await writeFile(join(DIST, '.deploy-info.json'), infoText, 'utf8');

console.log(`  version   ${APP_VERSION}`);
console.log(`  build     ${buildId}`);
console.log(`  files     ${allFiles.length + 1}`);
console.log(`  size      ${formatBytes(metadataBytes)}`);
console.log(`  output    ${DIST}`);
console.log(`  cache     ${corePaths.length} core entries verified`);
console.log('\n  dist/ 可直接上传到 Netlify / Cloudflare Pages / Vercel，或使用 deploy/Caddyfile 自托管。\n');

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(0)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
}
